const keys = Object.keys(starts19O).map(Number).sort((a,b)=>a-b);
let lastEnd = 0;
let errors = 0;

for (let i = 0; i < keys.length; i++) {
  const k = keys[i];
  const s = starts19O[k];
  let e;
  if (i < keys.length - 1) {
    e = starts19O[keys[i + 1]] - 1;
  } else {
    e = 165;
  }
  if (s !== lastEnd + 1) {
    console.error(`GAP ERROR at photo ${k}: expected ${lastEnd + 1}, got ${s}`);
    errors++;
  }
  lastEnd = e;
}

if (errors === 0 && lastEnd === 165) {
  console.log(`SUCCESS! All ${keys.length} items span strictly continuous 01 to 165 with 0 gaps!`);
} else {
  console.error(`FAILED with ${errors} errors, lastEnd = ${lastEnd}`);
}
